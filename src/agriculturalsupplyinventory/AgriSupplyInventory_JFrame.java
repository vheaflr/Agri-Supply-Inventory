    private void addButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addButtonActionPerformed
       String name = nameField.getText().trim();
       String category = categoryComboBox.getSelectedItem().toString();
       String quantityText = quantityField.getText().trim();

       String unit = unitComboBox.getSelectedItem().toString();

 // Validate product name
    if (name.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter the product name!");
        return;
    }

    // Validate category
    if (categoryComboBox.getSelectedIndex() == 0) {
        JOptionPane.showMessageDialog(this,
                "Please select a category!");
        return;
    }

    // Validate quantity
    if (quantityText.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter the quantity!");
        return;
    }

    // Validate unit
    if (unitComboBox.getSelectedIndex() == 0) {
        JOptionPane.showMessageDialog(this,
                "Please select a unit!");
        return;
    }

    try {
        int quantity = Integer.parseInt(quantityText);

        if (quantity < 0) {
            JOptionPane.showMessageDialog(this,
                    "Quantity cannot be negative!");
            return;
        }

        boolean added = inventory.addProduct(
                name, category, quantity, unit
        );

        if (added) {
            JOptionPane.showMessageDialog(this,
                    "Product added successfully!");

            nameField.setText("");
            categoryComboBox.setSelectedIndex(0);
            quantityField.setText("");
            unitComboBox.setSelectedIndex(0);

            displayInventory();

        } else {
            JOptionPane.showMessageDialog(this,
                    "Inventory is full!");
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Please enter a valid quantity!");
    }

    }//GEN-LAST:event_addButtonActionPerformed

    private void displayButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_displayButtonActionPerformed
    if (inventory.getCount() == 0) {
        JOptionPane.showMessageDialog(this,
                "No products added!");
        return;
    }
        DefaultTableModel model =
            (DefaultTableModel) inventoryTable.getModel();

    model.setRowCount(0);

    Products[] products = inventory.getProducts();

    for (int i = 0; i < inventory.getCount(); i++) {
        model.addRow(new Object[]{
            products[i].getProductId(),
            products[i].getProductName(),
            products[i].getCategory(),
            products[i].getQuantity(),
            products[i].getUnit()
        });
    }
    }//GEN-LAST:event_displayButtonActionPerformed

    private void searchButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchButtonActionPerformed
    String searchName = searchField.getText().trim();

    if (searchName.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter a product name.");
        return;
    }

    Products found = inventory.searchProduct(searchName);

    DefaultTableModel model =
            (DefaultTableModel) inventoryTable.getModel();

    model.setRowCount(0);

    if (found != null) {
        model.addRow(new Object[]{
            found.getProductId(),
            found.getProductName(),
            found.getCategory(),
            found.getQuantity(),
            found.getUnit()
        });
    } else {
        JOptionPane.showMessageDialog(this, "Product not found!");
    }
    }//GEN-LAST:event_searchButtonActionPerformed

    private void updateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateButtonActionPerformed
        int selectedRow = inventoryTable.getSelectedRow();

if (selectedRow == -1) {
    JOptionPane.showMessageDialog(this,
            "Please select a product from the table.");
    return;
}

String productId = inventoryTable.getValueAt(
        selectedRow, 0).toString();

String input = JOptionPane.showInputDialog(this,
        "Enter the new quantity:");

if (input == null) {
    return;
}

try {
    int newQuantity = Integer.parseInt(input);

    if (newQuantity < 0) {
        JOptionPane.showMessageDialog(this,
                "Quantity cannot be negative.");
        return;
    }

    boolean updated = inventory.updateStock(
            productId, newQuantity);

    if (updated) {
        JOptionPane.showMessageDialog(this,
                "Stock updated successfully!");

        displayInventory();
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "Please enter a valid whole number.");
}
    }//GEN-LAST:event_updateButtonActionPerformed

    private void deleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteButtonActionPerformed
        int selectedRow = inventoryTable.getSelectedRow();

if (selectedRow == -1) {
    JOptionPane.showMessageDialog(this,
            "Please select a product to delete.");
    return;
}

String productId = inventoryTable.getValueAt(
        selectedRow, 0).toString();

int confirm = JOptionPane.showConfirmDialog(this,
        "Are you sure you want to delete this product?",
        "Confirm Delete",
        JOptionPane.YES_NO_OPTION);

if (confirm == JOptionPane.YES_OPTION) {

    boolean deleted = inventory.deleteProduct(productId);

    if (deleted) {
        JOptionPane.showMessageDialog(this,
                "Product deleted successfully!");

        displayInventory();
    } else {
        JOptionPane.showMessageDialog(this,
                "Product could not be deleted.");
    }
}
    }//GEN-LAST:event_deleteButtonActionPerformed

