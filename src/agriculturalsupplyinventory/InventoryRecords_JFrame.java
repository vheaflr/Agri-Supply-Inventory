private void displayCategoryTables() {

    DefaultTableModel seedsModel =
            (DefaultTableModel) seedsTable.getModel();

    DefaultTableModel fertilizerModel =
            (DefaultTableModel) fertilizersTable.getModel();

    DefaultTableModel pesticidesModel =
            (DefaultTableModel) pesticidesTable.getModel();

    DefaultTableModel toolsModel =
            (DefaultTableModel) toolsTable.getModel();

    DefaultTableModel equipmentModel =
            (DefaultTableModel) equipmentsTable.getModel();
   

    // Clear all tables
    seedsModel.setRowCount(0);
    fertilizerModel.setRowCount(0);
    pesticidesModel.setRowCount(0);
    toolsModel.setRowCount(0);
    equipmentModel.setRowCount(0);


    // Get inventory array
    Products[] products = inventory.getProducts();

    // Display products according to category
    for (int i = 0; i < inventory.getCount(); i++) {

        Products product = products[i];

        Object[] row = {
            product.getProductId(),
            product.getProductName(),
            product.getCategory(),
            product.getQuantity(),
            product.getUnit()
        };

        String category = product.getCategory().trim();

        switch (category.toLowerCase()) {

            case "seeds":
                seedsModel.addRow(row);
                break;

            case "fertilizer":
                fertilizerModel.addRow(row);
                break;

            case "pesticides":
                pesticidesModel.addRow(row);
                break;

            case "tools":
                toolsModel.addRow(row);
                break;

            case "equipment":
                equipmentModel.addRow(row);
                break;
        }
    }
}
